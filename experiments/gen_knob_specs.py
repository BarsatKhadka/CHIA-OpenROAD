"""Regenerate chia_openroad/knob_specs.py from ORFS's machine-readable variable table.

`flow/scripts/variables.json` is the source ORFS generates its own
documentation from, so it beats parsing the rendered markdown. It gives us,
per variable: which stages read it, an optional type, an optional default,
whether ORFS considers it `tunable`, and whether it is deprecated.

What it does NOT give us is ranges — no min/max/choices field exists. Sane
bounds are design- and PDK-specific anyway (CORE_UTILIZATION has roughly a
+-2 window around 38 on gcd/sky130hd), so those have to come from calibration,
not from a static table.

    python experiments/gen_knob_specs.py external/OpenROAD-flow-scripts
"""
import json
import subprocess
import sys
from pathlib import Path

orfs = Path(sys.argv[1] if len(sys.argv) > 1 else "external/OpenROAD-flow-scripts")
spec = json.loads((orfs / "flow/scripts/variables.json").read_text())

# ORFS documents grt and route separately; the Makefile has one `route` target.
# `final` is the `finish` target. Anything else we ignore for ordering.
STAGE_MAP = {"synth": "synth", "floorplan": "floorplan", "place": "place",
             "cts": "cts", "grt": "route", "route": "route", "final": "finish"}
ORDER = ["synth", "floorplan", "place", "cts", "route", "finish"]

stage, vtype, default, tunable, deprecated = {}, {}, {}, [], []
for name, meta in spec.items():
    targets = [STAGE_MAP[s] for s in meta.get("stages", []) if s in STAGE_MAP]
    if targets:
        stage[name] = min(targets, key=ORDER.index)
    if meta.get("type"):
        vtype[name] = meta["type"]
    if "default" in meta:
        default[name] = meta["default"]
    if meta.get("tunable"):
        tunable.append(name)
    if meta.get("deprecated"):
        deprecated.append(name)

version = subprocess.run(["git", "-C", str(orfs), "describe", "--tags", "--always"],
                         capture_output=True, text=True).stdout.strip() or "unknown"

out = Path("chia_openroad/knob_specs.py")
with out.open("w") as f:
    f.write(f'''"""What ORFS make variables exist, what they mean, and when they take effect.

GENERATED by experiments/gen_knob_specs.py from ORFS's own
flow/scripts/variables.json — do not hand-edit; regenerate instead.
ORFS version: {version}   ({len(spec)} variables)

Three things come from ORFS and are authoritative:

  KNOB_STAGE  the EARLIEST stage a variable takes effect. A variable read by
              several stages is listed under all of them; the earliest is what
              matters, because changing it makes every stage from there stale.
  KNOB_TYPE   declared type — only {len(vtype)} of {len(spec)} variables declare one.
  TUNABLE     the {len(tunable)} variables ORFS itself marks `tunable`.

One thing does NOT come from ORFS: ranges. variables.json has no min/max or
choices field, and sane bounds are design- and PDK-specific regardless —
CORE_UTILIZATION has roughly a +-2 window around 38 on gcd/sky130hd, and
would have a different one elsewhere. Ranges must come from per-design
calibration, not from here.
"""

#: Flow order; index comparisons decide which stage is earlier.
STAGE_ORDER = {ORDER!r}

#: Every variable ORFS documents. Membership is the existence check —
#: a name outside this set is a typo, and make would silently ignore it.
KNOWN = frozenset({sorted(spec)!r})

#: Variables ORFS marks tunable. A conservative set: it omits PLACE_DENSITY,
#: GPL_TIMING_DRIVEN and ROUTING_LAYER_ADJUSTMENT, all of which ORFS AutoTuner
#: does sweep. Treat it as a strong prior for a legal-knob list, not the whole.
TUNABLE = frozenset({sorted(tunable)!r})

#: Deprecated variables — accepting one silently would be a trap.
DEPRECATED = frozenset({sorted(deprecated)!r})

#: variable -> earliest stage it affects.
KNOB_STAGE = {{
''')
    for k in sorted(stage):
        f.write(f'    {k!r}: {stage[k]!r},\n')
    f.write("}\n\n#: variable -> declared type, where ORFS declares one.\nKNOB_TYPE = {\n")
    for k in sorted(vtype):
        f.write(f'    {k!r}: {vtype[k]!r},\n')
    f.write("}\n\n#: variable -> ORFS default, where one is declared.\nKNOB_DEFAULT = {\n")
    for k in sorted(default):
        f.write(f'    {k!r}: {default[k]!r},\n')
    f.write("}\n")

print(f"wrote {out}")
print(f"  known={len(spec)}  staged={len(stage)}  typed={len(vtype)}  "
      f"tunable={len(tunable)}  deprecated={len(deprecated)}")
print(f"  deprecated: {deprecated}")
